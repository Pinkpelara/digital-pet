export function personalityShift(id: NonNullable<CatalogItem["personalityId"]>): Partial<PersonalityStats> {
  switch (id) {
    case "chaotic":
      return { chaos: 28, energy: 12, shy: -10 };
    case "dramatic":
      return { drama: 30, energy: 8 };
    case "sleepy":
      return { energy: -24, shy: 8, cling: 6 };
    case "shy":
      return { shy: 28, cling: -6, chaos: -8 };
    case "clingy":
      return { cling: 30, shy: -8 };
    case "explorer":
      return { curiosity: 26, energy: 10, shy: -6 };
  }
}

